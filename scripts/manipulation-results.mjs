#!/usr/bin/env node
// Regenerates test/fixtures/manipulation/RESULTS.md: the spec 7.2 table
// measured with the pinned cccc binary, plus the trigger firing matrix.
//
//   node --experimental-strip-types scripts/manipulation-results.mjs
//
// The TypeScript sources use NodeNext `.js` specifiers, so a tiny resolve
// hook maps `./x.js` to `./x.ts` when only the TypeScript file exists.

import { existsSync, writeFileSync } from "node:fs";
import { register } from "node:module";
import { fileURLToPath, pathToFileURL } from "node:url";

const hook = `
import { existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
export async function resolve(specifier, context, next) {
  if (specifier.endsWith(".js") && (specifier.startsWith(".") || specifier.startsWith("/"))) {
    const url = new URL(specifier, context.parentURL);
    if (url.protocol === "file:" && !existsSync(fileURLToPath(url))) {
      const ts = new URL(url.href.slice(0, -3) + ".ts");
      if (existsSync(fileURLToPath(ts))) return next(ts.href, context);
    }
  }
  return next(specifier, context);
}`;
register(`data:text/javascript,${encodeURIComponent(hook)}`, pathToFileURL("./"));

const root = new URL("../", import.meta.url);
const { analyzeVariant } = await import(new URL("test/complexity/analyze.ts", root).href);
const { VARIANTS } = await import(new URL("test/complexity/variants.ts", root).href);

// Spec 7.2 numbers: units, max CogC/CC, ΣCogC, V, Codex verdict.
const SPEC = {
  original: ["1", "24 / 17", "24", "16", "FAIL"],
  a: ["5", "5 / 5", "15", "14", "PASS"],
  "a′": ["4", "9 / 8", "16", "16", "PASS"],
  b: ["12", "2 / 4", "15", "16", "PASS"],
  c: ["23", "4 / 5", "6", "6", "PASS"],
  d: ["8", "2 / 4", "9", "10", "PASS"],
  "d′": ["5", "4 / 6", "13", "15", "PASS"],
  e: ["4", "0 / 1", "0 (+25)", "15", "module FAIL"],
  "e′": ["2", "0 / 1", "0 (+19)", "10", "module FAIL"],
  "e″": ["0", "—", "0 (+28)", "11", "module FAIL"],
  f: ["1", "1 / 2", "1", "1", "PASS"],
  "f′": ["1", "4 / 5", "4", "4", "PASS"],
  "f″": ["22", "1 / 3", "2", "4", "PASS"],
  g: ["2", "17 / 12", "18", "12", "FAIL"],
  h: ["4", "10 / 8", "16", "13", "PASS"],
  i: ["0", "—", "0", "0", "PASS"],
  "i′": ["11", "8 / 8", "12", "10", "PASS"],
  j: ["7", "7 / 8", "13", "13", "PASS"],
};

const rows = [await analyzeVariant({ id: "original", dir: "original", description: "원본", kind: "manipulation" })];
for (const v of VARIANTS) rows.push(await analyzeVariant(v));

const ALL = ["S1", "S2", "S5", "S9", "S10", "S11"];
const mark = (list, id) => (list.includes(id) ? "●" : "");
const out = [];
out.push("# Spec 7.2 manipulation experiment — measured");
out.push("");
out.push("Generated by `node --experimental-strip-types scripts/manipulation-results.mjs` with cccc v1.8.5 (af2abb8).");
out.push("All variants are checked against the original on 5,000 seeded random orders (`test/complexity/equivalence.test.ts`).");
out.push("");
out.push("*New code*: B has no pricing code, so every unit is new (limit 15) — the spec's \"Codex 설계 판정\" column.");
out.push("*Legacy*: B holds the original (CogC 24), C holds the variant — what S1/S5/S9/S10 compare.");
out.push("");
out.push("| 변환 | 분류 | 단위 | 최대 CogC / CC | ΣCogC (+residue) | V | G1 (new code) | spec: 단위 · 최대 · Σ · V · 판정 |");
out.push("|---|---|---:|---|---:|---:|---|---|");
for (const r of rows) {
  const s = SPEC[r.id] ?? [];
  const sum = r.residueCognitive > 0 ? `${r.sumCognitive} (+${r.residueCognitive})` : `${r.sumCognitive}`;
  const verdict = r.newCodeVerdict === "FAIL" ? `**FAIL** ${r.newCodeReasons.join(", ")}` : "PASS";
  out.push(`| ${r.id} | ${r.kind} | ${r.units} | ${r.maxCognitive} / ${r.maxCyclomatic} | ${sum} | ${r.visibleBranches} | ${verdict} | ${s.join(" · ")} |`);
}
out.push("");
out.push("## Routing triggers fired by G1 (● = fired)");
out.push("");
out.push(`| 변환 | legacy: ${ALL.join(" | ")} | new code: ${ALL.join(" | ")} |`);
out.push(`|---|${ALL.map(() => ":-:").join("|")}|${ALL.map(() => ":-:").join("|")}|`);
for (const r of rows) {
  out.push(`| ${r.id} | ${ALL.map((id) => mark(r.legacyTriggers, id)).join(" | ")} | ${ALL.map((id) => mark(r.newTriggers, id)).join(" | ")} |`);
}
out.push("");
out.push("## Trigger evidence (legacy setting)");
out.push("");
for (const r of rows) {
  const hits = r.legacy.outcome.triggers.filter((t) => t.routing);
  if (hits.length === 0) continue;
  out.push(`- **${r.id}**: ${hits.map((t) => `${t.id} — ${t.evidence}`).join("; ")}`);
}
out.push("");
const target = fileURLToPath(new URL("test/fixtures/manipulation/RESULTS.md", root));
writeFileSync(target, out.join("\n"));
console.log(out.join("\n"));
void existsSync;

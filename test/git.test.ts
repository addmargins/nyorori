import { expect, test } from 'vitest'
import { parseDiff } from '../src/git.ts'

test('parseDiff collects the hunks, the added and modified lines, and the old blob per file in the new version', () => {
  const blob = 'e7508fb0a1b2c3d4e5f60718293a4b5c6d7e8f90'
  const diff = [
    'diff --git a/src/a.ts b/src/a.ts',
    `index ${blob}..8b8a2f8a1b2c3d4e5f60718293a4b5c6d7e8f901 100644`,
    '--- a/src/a.ts',
    '+++ b/src/a.ts',
    '@@ -2 +2 @@ export function a() {',
    '-  return 1',
    '+  return 2',
    '@@ -10,0 +11,3 @@',
    '+x',
    // Hunk text that looks like headers.
    '+++ b/fake.ts',
    '+@@ -1 +1 @@',
    '@@ -20,2 +23,0 @@',
    '---- a/gone',
    '-gone',
    'diff --git a/old.ts b/new.ts',
    'similarity index 90%',
    'rename from old.ts',
    'rename to new.ts',
    `index ${blob}..0000000000000000000000000000000000000000 100644`,
    '--- a/old.ts',
    '+++ b/new.ts',
    '@@ -1 +1,2 @@',
    '-old',
    '\\ No newline at end of file',
    '+added',
    '+more',
    'diff --git a/added.ts b/added.ts',
    'new file mode 100644',
    'index 0000000000000000000000000000000000000000..8b8a2f8a1b2c3d4e5f60718293a4b5c6d7e8f901',
    '--- /dev/null',
    '+++ b/added.ts',
    '@@ -0,0 +1 @@',
    '+new',
    'diff --git a/deleted.ts b/deleted.ts',
    'deleted file mode 100644',
    `index ${blob}..0000000000000000000000000000000000000000`,
    '--- a/deleted.ts',
    '+++ /dev/null',
    '@@ -1 +0,0 @@',
    '-bye',
    'diff --git a/only-removed.ts b/only-removed.ts',
    `index ${blob}..8b8a2f8a1b2c3d4e5f60718293a4b5c6d7e8f901 100644`,
    '--- a/only-removed.ts',
    '+++ b/only-removed.ts',
    '@@ -3 +2,0 @@',
    '-bye',
    'diff --git a/mode.ts b/mode.ts',
    'old mode 100644',
    'new mode 100755',
    // Git ends a name with a space in it with a tab, and quotes a name with a quote in it.
    'diff --git a/with space.ts b/with space.ts',
    `index ${blob}..8b8a2f8a1b2c3d4e5f60718293a4b5c6d7e8f901 100644`,
    '--- a/with space.ts\t',
    '+++ b/with space.ts\t',
    '@@ -1 +1 @@',
    '-a',
    '+b',
    'diff --git "a/q\\"x.ts" "b/q\\"x.ts"',
    `index ${blob}..8b8a2f8a1b2c3d4e5f60718293a4b5c6d7e8f901 100644`,
    '--- "a/q\\"x.ts"',
    '+++ "b/q\\"x.ts"',
    '@@ -1 +1 @@',
    '-a',
    '+b',
  ].join('\n')
  const result = parseDiff(diff, '/repo')
  expect(Object.fromEntries([...result].map(([file, { lines, hunks, blob }]) => [file, { lines: [...lines], hunks: hunks.map((h) => `-${h.oldStart},${h.oldCount} +${h.newStart},${h.newCount}`), blob }]))).toEqual({
    '/repo/src/a.ts': { lines: [2, 11, 12, 13], hunks: ['-2,1 +2,1', '-10,0 +11,3', '-20,2 +23,0'], blob },
    '/repo/new.ts': { lines: [1, 2], hunks: ['-1,1 +1,2'], blob },
    '/repo/added.ts': { lines: [1], hunks: ['-0,0 +1,1'], blob: undefined },
    // Nothing added, but a deletion can still change an expression around it.
    '/repo/only-removed.ts': { lines: [], hunks: ['-3,1 +2,0'], blob },
    '/repo/with space.ts': { lines: [1], hunks: ['-1,1 +1,1'], blob },
    '/repo/q"x.ts': { lines: [1], hunks: ['-1,1 +1,1'], blob },
  })
})
